"""Build restaurants.js from the checked chain menus in tools/restaurants/.

Each TSV holds one chain's per-serving carbohydrate figures, copied from that
chain's own published nutrition guide (see sources.json). Every figure was read
at least twice from the source and only kept when the reads agreed.

    python3 tools/build_restaurants.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT.parent / "restaurants.js"


def main():
    chains = []
    for src in json.loads((ROOT / "restaurants" / "sources.json").read_text()):
        items = []
        with open(ROOT / "restaurants" / src["file"], newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f, delimiter="\t"):
                carbs = float(row["carbs_g"])
                items.append([row["section"].strip(), row["name"].strip(), carbs])
        chains.append({k: src[k] for k in ("chain", "source", "url", "date")} | {"items": items})
        print(f"{src['chain']}: {len(items)} items")
    OUT.write_text("// Generated by tools/build_restaurants.py from each chain's published nutrition guide. Do not edit by hand.\n"
                   "window.BOLUS_CHAINS = " + json.dumps(chains, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")


if __name__ == "__main__":
    main()
